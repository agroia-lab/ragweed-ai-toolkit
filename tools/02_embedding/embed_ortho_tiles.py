#!/usr/bin/env python3
"""
Orthomosaic Tile Embedding CLI
===============================

Computes ResNet50 (or other backbone) embeddings from orthomosaic tiles
generated by tile_orthomosaic.py, then applies dimensionality reduction
(UMAP, PCA, t-SNE) and creates interactive visualizations.

Relationship to tile_orthomosaic.py:
    tile_orthomosaic.py splits a large orthomosaic GeoTIFF into 1024x1024
    JPEG tiles and produces a tile_manifest.csv with spatial metadata.
    This script takes those tiles as input, computes deep feature embeddings,
    and visualizes the embedding space colored by spatial position, row,
    or valid pixel fraction.

Usage:
    python scripts/cli/embed_ortho_tiles.py \\
        --tiles /path/to/ortho_tiles_1024/ \\
        --output /path/to/embeddings_output/ \\
        --model resnet50 --batch-size 32 --device cuda:0

    # Quick test with subset
    python scripts/cli/embed_ortho_tiles.py \\
        --tiles /path/to/ortho_tiles_1024/ \\
        --max-samples 200 --skip-tsne

Output:
    - embeddings.npz: Raw embeddings + metadata arrays
    - embeddings_reduced.csv: Reduced coordinates with tile metadata
    - embedding_summary.json: Configuration and statistics
    - umap_by_grid_zone.html: UMAP colored by spatial zone (3x3 grid)
    - umap_by_row.html: UMAP colored by row index (N-S gradient)
    - umap_by_valid_frac.html: UMAP colored by valid pixel fraction
    - pca_by_grid_zone.html: PCA colored by spatial zone
"""

