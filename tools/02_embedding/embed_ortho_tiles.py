def parse_args():
    """Parse command-line arguments."""
    parser = argparse.ArgumentParser(
        description="Compute ResNet50 embeddings from orthomosaic tiles and visualize with UMAP/PCA.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""\
Examples:
  # Basic usage (auto-detect manifest and output dir)
  python scripts/cli/embed_ortho_tiles.py --tiles /path/to/ortho_tiles_1024/

  # Full options
  python scripts/cli/embed_ortho_tiles.py \\
      --tiles /path/to/ortho_tiles_1024/ \\
      --manifest /path/to/tile_manifest.csv \\
      --output /path/to/embeddings_output/ \\
      --model resnet50 --batch-size 32 --device cuda:0

  # Quick test with 200 tiles, skip t-SNE
  python scripts/cli/embed_ortho_tiles.py \\
      --tiles /path/to/ortho_tiles_1024/ \\
      --max-samples 200 --skip-tsne
""",
    )
    parser.add_argument(
        "--tiles",
        required=True,
        help="Path to directory containing JPEG tile images",
    )
    parser.add_argument(
        "--manifest",
        default=None,
        help="Path to tile_manifest.csv (default: looks inside --tiles dir)",
    )
    parser.add_argument(
        "--output",
        default=None,
        help="Output directory (default: <tiles_dir>/../ortho_embeddings/)",
    )
    parser.add_argument(
        "--model",
        default="resnet50",
        choices=["resnet50", "efficientnet_b0", "efficientnet_b2"],
        help="Backbone model for feature extraction (default: resnet50)",
    )
    parser.add_argument(
        "--batch-size",
        type=int,
        default=32,
        help="Batch size for inference (default: 32)",
    )
    parser.add_argument(
        "--max-samples",
        type=int,
        default=0,
        help="Limit number of tiles to process. 0 = all (default: 0)",
    )
    parser.add_argument(
        "--device",
        default=None,
        help="Device for inference, e.g. cuda:0 or cpu (default: auto-detect)",
    )
    parser.add_argument(
        "--skip-tsne",
        action="store_true",
        help="Skip t-SNE computation (saves time for large datasets)",
    )
    return parser.parse_args()


def main():
    """Main entry point for the orthomosaic tile embedding CLI."""
    args = parse_args()

    # =========================================================================
    # Banner
    # =========================================================================
    print("=" * 70)
    print("ORTHOMOSAIC TILE EMBEDDING PIPELINE")
    print("=" * 70)
    print(f"  Date     : {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}")
    print(f"  Tiles    : {args.tiles}")
    print(f"  Model    : {args.model}")
    print(f"  Batch    : {args.batch_size}")
    max_label = "all" if args.max_samples == 0 else str(args.max_samples)
    print(f"  Max tiles: {max_label}")
    print(f"  t-SNE    : {'skip' if args.skip_tsne else 'compute'}")

    # Resolve device
    if args.device is None:
        device = "cuda" if torch.cuda.is_available() else "cpu"
    else:
        device = args.device
    print(f"  Device   : {device}")

    # Resolve output directory
    tiles_dir = Path(args.tiles).resolve()
    if not tiles_dir.is_dir():
        print(f"\nERROR: Tiles directory does not exist: {tiles_dir}")
        sys.exit(1)

    if args.output is not None:
        output_dir = Path(args.output).resolve()
    else:
        output_dir = tiles_dir.parent / "ortho_embeddings"

    output_dir.mkdir(parents=True, exist_ok=True)
    print(f"  Output   : {output_dir}")
    print("=" * 70)
    print()

    # =========================================================================
    # [1/4] Load tiles
    # =========================================================================
    print("-" * 70)
    print("[1/4] Load tiles")
    print("-" * 70)

    transform = default_transform(image_size=224)

    dataset = TileDataset(
        tiles_dir=str(tiles_dir),
        manifest_path=args.manifest,
        transform=transform,
        max_samples=args.max_samples,
    )

    if len(dataset) == 0:
        print("\nERROR: No tile images found in the specified directory.")
        sys.exit(1)

    print()

    # =========================================================================
    # [2/4] Extract embeddings
    # =========================================================================
    print("-" * 70)
    print("[2/4] Extract embeddings")
    print("-" * 70)

    print(f"  Initializing {args.model} model...")
    model = FeatureExtractor(args.model)
    print(f"  Embedding dimension: {model.embedding_dim}")

    embeddings = extract_embeddings(
        images=dataset,
        model=model,
        batch_size=args.batch_size,
        num_workers=4,
        device=device,
    )
    print(f"  Embeddings shape: {embeddings.shape}")

    if embeddings.ndim != 2:
        print(f"ERROR: Embeddings must be 2D, got shape {embeddings.shape}")
        sys.exit(1)

    print()

    # =========================================================================
    # [3/4] Reduce dimensions
    # =========================================================================
    print("-" * 70)
    print("[3/4] Reduce dimensions")
    print("-" * 70)

    def _reduce(emb, method, n_components=2):
        """Thin wrapper: reduce_embeddings returns DataFrame, extract numpy."""
        df_r = reduce_embeddings(emb, method=method, n_components=n_components)
        prefix = method.lower()
        cols = [f"{prefix}_x", f"{prefix}_y"]
        if n_components >= 3:
            cols.append(f"{prefix}_z")
        return df_r[cols].values

    # UMAP 2D
    print("\n  [a] UMAP 2D...")
    try:
        umap_2d = _reduce(embeddings, "umap", 2)
    except ImportError:
        print(
            "\n  ERROR: umap-learn is not installed."
            "\n  Install it with: pip install umap-learn"
            "\n  or: conda install -c conda-forge umap-learn"
        )
        sys.exit(1)

    # PCA 2D
    print("\n  [b] PCA 2D...")
    pca_2d = _reduce(embeddings, "pca", 2)

    # t-SNE 2D (optional)
    tsne_2d = None
    if not args.skip_tsne:
        print("\n  [c] t-SNE 2D...")
        tsne_2d = _reduce(embeddings, "tsne", 2)
    else:
        print("\n  [c] t-SNE 2D... SKIPPED (--skip-tsne)")

    print()

    # =========================================================================
    # Build DataFrame
    # =========================================================================
    print("-" * 70)
    print("  Building results DataFrame...")
    print("-" * 70)

    df = pd.DataFrame(dataset.metadata)

    # Add reduced coordinates
    df["umap_x"] = umap_2d[:, 0]
    df["umap_y"] = umap_2d[:, 1]
    df["pca_x"] = pca_2d[:, 0]
    df["pca_y"] = pca_2d[:, 1]

    if tsne_2d is not None:
        df["tsne_x"] = tsne_2d[:, 0]
        df["tsne_y"] = tsne_2d[:, 1]

    # Compute grid_zone for tiles that have row/col metadata
    has_rowcol = df["row"].notna() & df["col"].notna()
    if has_rowcol.any():
        n_rows = int(df.loc[has_rowcol, "row"].max()) + 1
        n_cols = int(df.loc[has_rowcol, "col"].max()) + 1

        df["grid_zone"] = "unknown"
        for idx in df.index[has_rowcol]:
            df.at[idx, "grid_zone"] = compute_grid_zone(
                int(df.at[idx, "row"]),
                int(df.at[idx, "col"]),
                n_rows,
                n_cols,
            )

        # Convert row to string for categorical coloring
        df["row_str"] = df["row"].apply(
            lambda v: f"row_{int(v):03d}" if pd.notna(v) else "unknown"
        )
    else:
        df["grid_zone"] = "unknown"
        df["row_str"] = "unknown"

    # Ensure frac_valid is numeric
    if "frac_valid" in df.columns:
        df["frac_valid"] = pd.to_numeric(df["frac_valid"], errors="coerce")

    print(f"  Total tiles: {len(df)}")
    if has_rowcol.any():
        print(f"  Grid size: {n_rows} rows x {n_cols} cols")
        print(f"  Grid zones:")
        for zone, count in df["grid_zone"].value_counts().sort_index().items():
            print(f"    {zone}: {count}")
    print()

    # =========================================================================
    # [4/4] Create visualizations
    # =========================================================================
    print("-" * 70)
    print("[4/4] Create visualizations")
    print("-" * 70)

    # Check for plotly
    try:
        import plotly.express  # noqa: F401
    except ImportError:
        print(
            "\n  ERROR: plotly is not installed."
            "\n  Install it with: pip install plotly"
        )
        sys.exit(1)

    files_created = []

    # 1. UMAP by grid zone
    print("\n  [a] UMAP by grid zone...")
    fpath = str(output_dir / "umap_by_grid_zone.html")
    create_tile_visualization(
        df,
        x_col="umap_x",
        y_col="umap_y",
        color_col="grid_zone",
        title="UMAP - Tile Embeddings by Grid Zone (3x3)",
        output_path=fpath,
    )
    files_created.append("umap_by_grid_zone.html")

    # 2. UMAP by row
    print("\n  [b] UMAP by row index...")
    fpath = str(output_dir / "umap_by_row.html")
    create_tile_visualization(
        df,
        x_col="umap_x",
        y_col="umap_y",
        color_col="row_str",
        title="UMAP - Tile Embeddings by Row (N-S gradient)",
        output_path=fpath,
    )
    files_created.append("umap_by_row.html")

    # 3. UMAP by valid fraction (continuous color)
    if df["frac_valid"].notna().any():
        print("\n  [c] UMAP by valid pixel fraction...")
        fpath = str(output_dir / "umap_by_valid_frac.html")
        # Work on a copy that drops NaN frac_valid rows for this plot
        df_valid = df.dropna(subset=["frac_valid"]).copy()
        if len(df_valid) > 0:
            create_tile_visualization(
                df_valid,
                x_col="umap_x",
                y_col="umap_y",
                color_col="frac_valid",
                title="UMAP - Tile Embeddings by Valid Pixel Fraction",
                output_path=fpath,
                continuous_color=True,
            )
            files_created.append("umap_by_valid_frac.html")
        else:
            print("    Skipped: no valid frac_valid data")
    else:
        print("\n  [c] UMAP by valid fraction... Skipped (no frac_valid data)")

    # 4. PCA by grid zone
    print("\n  [d] PCA by grid zone...")
    fpath = str(output_dir / "pca_by_grid_zone.html")
    create_tile_visualization(
        df,
        x_col="pca_x",
        y_col="pca_y",
        color_col="grid_zone",
        title="PCA - Tile Embeddings by Grid Zone (3x3)",
        output_path=fpath,
    )
    files_created.append("pca_by_grid_zone.html")

    # 5. t-SNE by grid zone (if computed)
    if tsne_2d is not None:
        print("\n  [e] t-SNE by grid zone...")
        fpath = str(output_dir / "tsne_by_grid_zone.html")
        create_tile_visualization(
            df,
            x_col="tsne_x",
            y_col="tsne_y",
            color_col="grid_zone",
            title="t-SNE - Tile Embeddings by Grid Zone (3x3)",
            output_path=fpath,
        )
        files_created.append("tsne_by_grid_zone.html")

    print()

    # =========================================================================
    # Save outputs
    # =========================================================================
    print("-" * 70)
    print("  Saving outputs...")
    print("-" * 70)

    # 1. Raw embeddings (.npz)
    npz_path = output_dir / "embeddings.npz"

    # Build metadata array for downstream compatibility
    metadata_array = np.array([
        {
            'filename': m['filename'],
            'row': m.get('row'),
            'col': m.get('col'),
            'grid_zone': m.get('grid_zone', ''),
            'frac_valid': m.get('frac_valid', 1.0),
        }
        for m in dataset.metadata
    ], dtype=object)

    np.savez_compressed(
        npz_path,
        embeddings=embeddings,
        metadata=metadata_array,
        filenames=np.array([m["filename"] for m in dataset.metadata]),
        rows=np.array(
            [m.get("row", -1) if m.get("row") is not None else -1 for m in dataset.metadata],
            dtype=np.float32,
        ),
        cols=np.array(
            [m.get("col", -1) if m.get("col") is not None else -1 for m in dataset.metadata],
            dtype=np.float32,
        ),
    )
    print(f"  Saved: {npz_path}")
    files_created.append("embeddings.npz")

    # 2. Reduced embeddings CSV
    csv_path = output_dir / "embeddings_reduced.csv"
    # Drop full_path from CSV to keep it portable
    df_save = df.drop(columns=["full_path"], errors="ignore")
    df_save.to_csv(csv_path, index=False)
    print(f"  Saved: {csv_path}")
    files_created.append("embeddings_reduced.csv")

    # 3. Summary JSON
    summary = {
        "timestamp": datetime.now().isoformat(),
        "tiles_dir": str(tiles_dir),
        "output_dir": str(output_dir),
        "model": args.model,
        "device": device,
        "batch_size": args.batch_size,
        "n_tiles": len(df),
        "embedding_dim": int(embeddings.shape[1]),
        "max_samples": args.max_samples,
        "skip_tsne": args.skip_tsne,
        "reductions": ["umap_2d", "pca_2d"] + (["tsne_2d"] if tsne_2d is not None else []),
        "grid_zones": (
            df["grid_zone"].value_counts().to_dict()
            if has_rowcol.any()
            else {}
        ),
        "files_created": files_created,
    }

    # Add manifest info if available
    if dataset.manifest_df is not None:
        summary["manifest_path"] = str(
            Path(args.manifest).resolve() if args.manifest else tiles_dir / "tile_manifest.csv"
        )
        summary["manifest_rows"] = len(dataset.manifest_df)

    summary_path = output_dir / "embedding_summary.json"
    with open(summary_path, "w") as f:
        json.dump(summary, f, indent=2)
    print(f"  Saved: {summary_path}")
    files_created.append("embedding_summary.json")

    print()

    # =========================================================================
    # Final summary
    # =========================================================================
    print("=" * 70)
    print("PIPELINE COMPLETED SUCCESSFULLY")
    print("=" * 70)
    print()
    print(f"  Tiles processed : {len(df)}")
    print(f"  Embedding dim   : {embeddings.shape[1]}")
    print(f"  Output directory : {output_dir}")
    print()
    print("  Files created:")
    for f in sorted(output_dir.glob("*")):
        size = f.stat().st_size / 1024
        unit = "KB"
        if size > 1024:
            size /= 1024
            unit = "MB"
        print(f"    {f.name}: {size:.1f} {unit}")
    print()


