from ragweed_toolkit.embeddings import (
    FeatureExtractor,
    extract_embeddings,
    default_transform,
    reduce_embeddings,
)

# Suppress warnings for cleaner output
warnings.filterwarnings("ignore")


# ============================================================================
# TILE DATASET
# ============================================================================

class TileDataset(Dataset):
    """
    Dataset for loading orthomosaic tiles with optional manifest metadata.

    Scans a directory for .jpg tiles, loads the tile_manifest.csv if available,
    and attaches spatial metadata (row, col, georeferenced bounds, valid pixel
    fraction) to each tile.
    """

    def __init__(
        self,
        tiles_dir: str,
        manifest_path: Optional[str] = None,
        transform: Optional[transforms.Compose] = None,
        max_samples: int = 0,
    ):
        self.tiles_dir = Path(tiles_dir)
        self.transform = transform

        # Find all JPEG tiles
        extensions = {".jpg", ".jpeg", ".JPG", ".JPEG"}
        self.image_paths = []
        for ext in extensions:
            self.image_paths.extend(list(self.tiles_dir.glob(f"*{ext}")))
        self.image_paths.sort()

        # Limit samples if requested (0 = no limit)
        if max_samples > 0 and len(self.image_paths) > max_samples:
            self.image_paths = self.image_paths[:max_samples]

        # Load manifest if available
        self.manifest_df = None
        self._load_manifest(manifest_path)

        # Build metadata for each tile
        self.metadata = self._build_metadata()

        print(f"  Tiles found: {len(self.image_paths)}")
        if self.manifest_df is not None:
            print(f"  Manifest loaded: {len(self.manifest_df)} entries")
            matched = sum(1 for m in self.metadata if m.get("row") is not None)
            print(f"  Tiles matched to manifest: {matched}/{len(self.image_paths)}")
        else:
            print("  Manifest: not found (using filename-only metadata)")

    def _load_manifest(self, manifest_path: Optional[str]):
        """Load tile_manifest.csv with spatial metadata."""
        if manifest_path is not None:
            mp = Path(manifest_path)
        else:
            # Default: look inside tiles directory
            mp = self.tiles_dir / "tile_manifest.csv"

        if mp.exists():
            try:
                self.manifest_df = pd.read_csv(mp)
                # Ensure the filename column exists
                if "filename" not in self.manifest_df.columns:
                    # Try common alternatives
                    for col in ["tile_filename", "file", "name"]:
                        if col in self.manifest_df.columns:
                            self.manifest_df = self.manifest_df.rename(
                                columns={col: "filename"}
                            )
                            break
                if "filename" not in self.manifest_df.columns:
                    print(
                        f"  WARNING: Manifest at {mp} has no 'filename' column. "
                        f"Columns: {list(self.manifest_df.columns)}"
                    )
                    self.manifest_df = None
            except Exception as e:
                print(f"  WARNING: Could not read manifest {mp}: {e}")
                self.manifest_df = None
        else:
            if manifest_path is not None:
                print(f"  WARNING: Manifest not found at {manifest_path}")

    def _build_metadata(self) -> List[Dict]:
        """Build metadata list, merging manifest data where available."""
        metadata = []

        # Create a lookup from manifest if available
        manifest_lookup = {}
        if self.manifest_df is not None and "filename" in self.manifest_df.columns:
            for _, row in self.manifest_df.iterrows():
                manifest_lookup[row["filename"]] = row.to_dict()

        for path in self.image_paths:
            fname = path.name
            entry = {"filename": fname, "full_path": str(path)}

            if fname in manifest_lookup:
                mrow = manifest_lookup[fname]
                # Standard manifest columns from tile_orthomosaic.py
                for col in [
                    "row", "col", "x_min", "y_min", "x_max", "y_max", "frac_valid"
                ]:
                    entry[col] = mrow.get(col, None)
            else:
                # Try to parse row/col from filename pattern: tile_RRR_CCC.jpg
                parts = fname.replace(".jpg", "").replace(".jpeg", "").split("_")
                try:
                    # Attempt numeric parsing for patterns like tile_003_012.jpg
                    nums = [int(p) for p in parts if p.isdigit()]
                    if len(nums) >= 2:
                        entry["row"] = nums[0]
                        entry["col"] = nums[1]
                    else:
                        entry["row"] = None
                        entry["col"] = None
                except (ValueError, IndexError):
                    entry["row"] = None
                    entry["col"] = None

                entry["x_min"] = None
                entry["y_min"] = None
                entry["x_max"] = None
                entry["y_max"] = None
                entry["frac_valid"] = None

            metadata.append(entry)

        return metadata

    def __len__(self) -> int:
        return len(self.image_paths)

    def __getitem__(self, idx: int) -> Tuple[torch.Tensor, int]:
        img_path = self.image_paths[idx]

        try:
            image = Image.open(img_path).convert("RGB")
            if self.transform:
                image = self.transform(image)
            return image, idx
        except Exception as e:
            print(f"  Error loading {img_path}: {e}")
            # Return a blank tensor on error
            return torch.zeros(3, 224, 224), idx


# ============================================================================
# GRID ZONE COMPUTATION
# ============================================================================

def compute_grid_zone(
    row: int, col: int, n_rows: int, n_cols: int, grid_size: int = 3
) -> str:
    """
    Assign a tile to a spatial grid zone based on its row/col position.

    Divides the orthomosaic into a grid_size x grid_size grid and returns
    a human-readable zone label (e.g., "top-left", "center", "bot-right").

    Args:
        row: Tile row index
        col: Tile column index
        n_rows: Total number of rows in the tile grid
        n_cols: Total number of columns in the tile grid
        grid_size: Number of divisions per axis (default 3 for 3x3 = 9 zones)

    Returns:
        Zone label string
    """
    zone_labels = [
        ["top-left", "top-center", "top-right"],
        ["mid-left", "center", "mid-right"],
        ["bot-left", "bot-center", "bot-right"],
    ]
    r = min(int(row / n_rows * grid_size), grid_size - 1)
    c = min(int(col / n_cols * grid_size), grid_size - 1)
    return zone_labels[r][c]


# ============================================================================
# VISUALIZATION (adapted for tile metadata)
# ============================================================================

def create_tile_visualization(
    df: pd.DataFrame,
    x_col: str,
    y_col: str,
    color_col: str,
    title: str,
    output_path: str,
    continuous_color: bool = False,
):
    """
    Create an interactive scatter plot for tile embeddings.

    Similar to create_visualization() in generate_embeddings.py but uses
    tile-specific hover columns instead of the hardcoded location/source_type.

    Args:
        df: DataFrame with coordinates and tile metadata
        x_col, y_col: Column names for 2D coordinates
        color_col: Column to use for coloring points
        title: Plot title
        output_path: Output HTML file path
        continuous_color: If True, use continuous color scale (for numeric cols)
    """
    import plotly.express as px

    # Build hover data from available columns
    hover_cols = ["filename"]
    for col in ["row", "col", "grid_zone", "frac_valid"]:
        if col in df.columns and col != color_col:
            hover_cols.append(col)

    if continuous_color:
        fig = px.scatter(
            df,
            x=x_col,
            y=y_col,
            color=color_col,
            hover_data=hover_cols,
            title=title,
            opacity=0.7,
            color_continuous_scale="Viridis",
        )
    else:
        fig = px.scatter(
            df,
            x=x_col,
            y=y_col,
            color=color_col,
            hover_data=hover_cols,
            title=title,
            opacity=0.7,
        )

    fig.update_traces(marker=dict(size=5))
    fig.update_layout(
        template="plotly_white",
        width=1200,
        height=800,
        legend=dict(yanchor="top", y=0.99, xanchor="left", x=1.02),
    )

    fig.write_html(output_path)
    print(f"    Saved: {output_path}")

    # Try to save static PNG as well
    png_path = output_path.replace(".html", ".png")
    try:
        fig.write_image(png_path, scale=2)
        print(f"    Saved: {png_path}")
    except Exception:
        pass  # kaleido not installed; skip silently

    return fig


